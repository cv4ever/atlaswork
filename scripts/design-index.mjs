// Writes docs/design-index.md: every decision in docs/agents-design.md (D1, D2, …) with its title, its section, what
// its heading says about its history (superseded, extended), and the source files that cite it most, so an agent finds
// the code a decision governs in one step instead of reading 950 lines. Code cites a decision as `D61` or
// `agents-design D61` in a comment. Usage: node scripts/design-index.mjs (`--check` fails when the file is stale;
// `pnpm run lint` runs it so).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const target = "docs/design-index.md";
const doc = readFileSync("docs/agents-design.md", "utf8").split(/\r?\n/);
const decisions = [];
let section = "";
for (const line of doc) {
  const heading = /^###\s+(.*)/.exec(line);
  if (heading) { section = heading[1].trim(); continue; }
  const decision = /^- \*\*(D\d+) ([^*]+?)\.?\*\*(?: \(([^)]*)\))?/.exec(line);
  if (decision) decisions.push({ code: decision[1], title: decision[2].trim(), section, note: decision[3] ?? "" });
}

const files = execFileSync("git", ["ls-files", "--cached", "--others", "--exclude-standard", "src", "supabase/functions", "dev", "scripts"], { encoding: "utf8" })
  .split("\n").filter((file) => /\.(ts|tsx|mjs|css)$/.test(file) && !file.endsWith(".test.ts") && file !== "scripts/design-index.mjs");
const cited = new Map(decisions.map(({ code }) => [code, new Map()]));
for (const file of files) {
  let text;
  try { text = readFileSync(file, "utf8"); } catch { continue; }
  // "launch plan D2" cites docs/mvp-launch-plan.md, whose codes are its own.
  for (const match of text.matchAll(/(?<!plan )\bD(\d+)\b/g)) {
    const counts = cited.get(`D${match[1]}`);
    if (counts) counts.set(file, (counts.get(file) ?? 0) + 1);
  }
}
const top = (code) => [...cited.get(code)].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])).slice(0, 5).map(([file]) => `\`${file}\``).join(", ");
const cell = (text) => text.replaceAll("|", "\\|");
const body = [
  "# Decision index",
  "",
  "Every decision in [agents-design.md](agents-design.md), with the source files that cite it most (up to five; `rg -n \"\\bD61\\b\" src` finds every one).",
  "Generated by `node scripts/design-index.mjs` from the decisions' headings and the code's comments; `pnpm run lint` fails while it is stale, so rerun it after adding a decision or citing one.",
  "",
  "| Decision | Section | History | Cited most in |",
  "| --- | --- | --- | --- |",
  ...decisions.map(({ code, title, section, note }) => `| **${code}** ${cell(title)} | ${cell(section)} | ${cell(note)} | ${top(code) || "none yet"} |`),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  let current = "";
  try { current = readFileSync(target, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing counts as stale */ }
  if (current !== body) {
    console.error(`${target} is stale: run node scripts/design-index.mjs`);
    process.exit(1);
  }
} else writeFileSync(target, body);
